"""Построение промпта генерации сценария v2 (Сценарист v2).

Собирает единственный промпт для LLM-генерации ОДНОГО живого рекламного сценария:
роль креативного директора ACME + инъекция ТОЛЬКО разрешённых фактов из Fact Sheet
(fact_sheet.fact_sheet_for_prompt) + структура под формат темы (scenario_formats.format_instructions)
+ референс-креатив если есть + few-shot эталон стиля владельца (creative_briefs) +
явные guardrail-запреты (бюрократия, выдуманные числа/даты, смешение PRODA/PRODB, смешение голосов).

См. ARCH-phase3-scenarist.md §T5. Единственная публичная функция — build_scenario_prompt.
"""

from services.creative_briefs import _EXAMPLE_SPEAKER_MONOLOGUE, _EXAMPLE_STORYTELLING
from services.fact_sheet import fact_sheet_for_prompt
from services.scenario_formats import format_instructions

# Общие запреты для обоих голосов — бюрократия и выдуманные факты запрещены всегда.
_COMMON_GUARDRAILS = """ЗАПРЕЩЕНО (жёсткие правила, нарушение = карточка не пройдёт проверку и не будет создана):
- Использовать любое число (проценты, показатели, размер пакета, стоимость и т.п.), которого нет в блоке ФАКТЫ выше. Год (например 2026) и номера пакетов — можно, если они упомянуты в ФАКТАХ.
- Использовать любую дату или дедлайн («до 15 августа», «осталось 3 дня» и т.п.), которого нет в блоке ФАКТЫ/дедлайны выше. Абстрактную срочность («времени мало», «сезон короткий — решать надо сейчас») использовать МОЖНО.
- Смешивать PRODA и PRODB в одном сценарии: PRODA — пакеты 2 и 4, PRODB — только пакет 6. Не путать пакет клиента с продуктом другой линейки.
- Бюрократическую структуру полей: заголовки вида "Аудитория:", "Сообщение:", "Эмоция:", "Тон:", "Приоритет:", "Формат:", "Тип:" в теле сценария ЗАПРЕЩЕНЫ. Сценарий — цельный живой текст, а не таблица полей.
- Маркетинговый буллшит: "уникальная методика", "инновационный подход", "лучший в городе" и подобные пустые фразы.
- Выдумывать факты о ACME, которых нет в блоке ФАКТЫ (акции, гарантии, цифры, отзывы) — только то, что явно разрешено."""

# Запрет смешения голосов — специфичен под голос темы (кого запрещаем имитировать).
_VOICE_GUARDRAILS = {
    "brand": (
        "ГОЛОС: brand (от лица ACME/менеджера/спикера компании). "
        "ЗАПРЕЩЕНО использовать маркеры голоса testimonial (речь от лица клиента "
        'о личном опыте: "я записалась на консультацию", "я обратился", "я подключила", "я поняла, что..."). '
        "Пиши от лица компании или её сотрудника — «мы», «наш сервис», «ACME предлагает», «в ACME»."
    ),
    "testimonial": (
        "ГОЛОС: testimonial (от лица реального клиента, только по ФАКТАМ из блока «РЕАЛЬНЫЕ ОТЗЫВЫ» выше). "
        "ЗАПРЕЩЕНО использовать маркеры голоса brand (речь от лица компании: «мы в ACME», "
        '«наш сервис», «ACME предлагает») — весь текст от первого лица клиента. '
        "ЗАПРЕЩЕНО выдумывать детали истории, которых нет в разрешённом отзыве."
    ),
}


def build_scenario_prompt(topic: dict, fact_sheet: dict) -> str:
    """Строит промпт для LLM-генерации одного цельного рекламного сценария под тему.

    Args:
        topic: элемент из topic_selector.select_topics() — см. ARCH-phase3-scenarist.md §6.1
            (ключи: source, city, segment, voice, ad_format, reference, variable_to_vary,
            angle, priority, rationale)
        fact_sheet: dict из fact_sheet.load_fact_sheet()

    Returns:
        Готовый текстовый промпт (строка) для одного вызова LLM. Ответ модели — только
        текст сценария, без пояснений (это диктуется инструкцией в конце промпта).
    """
    voice = topic.get("voice", "brand")
    ad_format = topic.get("ad_format", "video_speaker")
    city = topic.get("city", "")
    segment = topic.get("segment", "общий")
    angle = topic.get("angle", "")
    reference = topic.get("reference")
    variable_to_vary = topic.get("variable_to_vary", "")
    rationale = topic.get("rationale", "")

    facts_block = fact_sheet_for_prompt(fact_sheet, voice)
    format_block = format_instructions(ad_format)
    voice_guardrail = _VOICE_GUARDRAILS.get(voice, _VOICE_GUARDRAILS["brand"])

    reference_block = ""
    if reference:
        reference_block = (
            "\n\nРЕФЕРЕНС (наш лучший ролик на эту тему — что уже сработало, варьируй "
            f"именно «{variable_to_vary}», остальное держи близко к референсу):\n"
            f"- {reference.get('name', '?')} — CPL ${reference.get('cpl', '?')}, "
            f"{reference.get('leads', '?')} лидов, {reference.get('payments', '?')} оплат."
        )

    context_lines = [f"Город: {city}", f"Сегмент: {segment}"]
    if angle:
        context_lines.append(f"Угол/тема: {angle}")
    if rationale:
        context_lines.append(f"Почему эта тема: {rationale}")
    context_block = "\n".join(f"- {line}" for line in context_lines)

    return f"""Ты — креативный директор сервиса ACME (продуктовые линейки PRODA и PRODB). Ты пишешь ТЗ для рекламы так, как их пишет реальный владелец бизнеса — не маркетолог с шаблонами, а человек, который сам придумывает живые сценарии.

=== ФАКТЫ (единственный разрешённый источник цифр, дат и утверждений о ACME) ===
{facts_block}

=== СТРУКТУРА ФОРМАТА (обязательна) ===
{format_block}

=== ЭТАЛОН СТИЛЯ ВЛАДЕЛЬЦА (копируй уровень живости и конкретики, НЕ копируй текст дословно) ===

--- Пример 1: спикер-монолог (короткий, ~600-800 символов) ---
{_EXAMPLE_SPEAKER_MONOLOGUE}

--- Пример 2: сторителлинг (длинный, ~2000-3500 символов; стиль-эталон — используется даже если голос testimonial сейчас заблокирован) ---
{_EXAMPLE_STORYTELLING}

Что общего у обоих примеров (обязательно повтори):
- Цельный живой текст от начала до конца, а НЕ таблица полей.
- Разговорный русский, без маркетингового буллшита.
- Конкретные детали и термины (PRODA, PRODB, пакет услуг, персональный менеджер, рассрочка) — но ТОЛЬКО из блока ФАКТЫ выше, не выдуманные.
- Диалоги в кавычках-ёлочках «...», где уместно.

=== ТЕМА ЭТОГО СЦЕНАРИЯ ===
{context_block}
{reference_block}

=== GUARDRAILS (обязательны к соблюдению) ===
{voice_guardrail}

{_COMMON_GUARDRAILS}

=== ЗАДАЧА ===
Напиши ОДИН цельный сценарий (только один вариант, не 3) под формат «{ad_format}» и тему выше.

ФОРМАТ ОТВЕТА (строго):
- Верни ТОЛЬКО текст сценария — без вступлений вроде "Вот сценарий:", без markdown-заголовков, без нумерации полей, без пояснений от себя.
- Соблюдай обязательные маркеры разметки формата из блока СТРУКТУРА ФОРМАТА выше.
- Пиши на русском."""
