"""
Единый форматтер денежных сумм для Telegram-отчётов автопилота.

Правило: разделитель разрядов (тысяч) — точка, а не запятая/пробел
(например, 1.500.000), и рядом с суммой всегда должен быть символ валюты.

Примеры:
    fmt_money(2500, "$")        -> "$2.500"
    fmt_money(1500000, "¤")     -> "¤ 1.500.000"
    fmt_money(67.5, "$")        -> "$67.5"   (дробная часть — для сумм < 100)
    fmt_money(67, "$")          -> "$67"
    fmt_money(None, "$")        -> "$—"
"""


def fmt_money(value: float | int | None, currency: str = "$") -> str:
    """Форматирует денежную сумму по единому правилу.

    - Тысячи разделяются точкой: 1500000 -> "1.500.000".
    - Для сумм >= 100 дробная часть отбрасывается (округление до целого).
    - Для сумм < 100 с дробной частью — одна цифра после запятой
      (округление до 0.1), для целых < 100 — без дробной части.
    - "$" (доллар) прижимается к числу без пробела: "$2.500".
    - "¤" (ед.) отделяется пробелом от числа: "¤ 1.500.000" — так
      привычнее читать ед. по-русски («¤ 1.500.000», а не «1.500.000¤»).
    - None -> "{currency}—" (нет данных, а не фиктивный 0).

    Args:
        value: сумма (может быть отрицательной — знак минус сохраняется перед числом).
        currency: "$" или "¤" (по умолчанию доллар).

    Returns:
        Готовая строка для вставки в Telegram-сообщение.
    """
    if value is None:
        sep = " " if currency == "¤" else ""
        return f"{currency}{sep}—"

    negative = value < 0
    abs_value = abs(value)

    if abs_value >= 100 or float(abs_value).is_integer():
        # Целые суммы (или крупные) — без дробной части
        int_part = f"{round(abs_value):,}".replace(",", ".")
        number_str = int_part
    else:
        # Дробные суммы < 100 — одна цифра после запятой
        rounded = round(abs_value, 1)
        int_part, _, frac_part = f"{rounded:.1f}".partition(".")
        int_part = f"{int(int_part):,}".replace(",", ".")
        number_str = f"{int_part}.{frac_part}"

    sign = "-" if negative else ""
    sep = " " if currency == "¤" else ""
    return f"{sign}{currency}{sep}{number_str}"


def truncate_at_word_boundary(text: str, max_len: int) -> str:
    """Обрезает строку по границе слова (не посреди слова) с многоточием.

    Общая утилита для всех Telegram-отчётов, где текст режется по лимиту
    (причины пауз в autopilot.py, подписи inline-кнопок в auto_launch.py).
    Раньше text[:N] резал фразу посреди слова — нечитаемо и владелец против
    таких обрубков. Ищем последний пробел до max_len и режем там; если
    пробела нет — режем жёстко (страховка от бесконечно длинного «слова»
    без пробелов).

    Примеры:
        truncate_at_word_boundary("Петров / Тестовая подтема", 22)
            -> "Петров / Тестовая…"
        truncate_at_word_boundary("Коротко", 22) -> "Коротко"  (без изменений)

    Args:
        text: исходная строка.
        max_len: максимальная длина ДО добавления многоточия.

    Returns:
        text без изменений, если len(text) <= max_len, иначе обрезанная
        по слову строка с "…" в конце.
    """
    if len(text) <= max_len:
        return text
    cut = text.rfind(" ", 0, max_len)
    if cut <= 0:
        cut = max_len
    return text[:cut].rstrip(" ,;") + "…"


def pluralize_leads(n: int | None) -> str:
    """Русское склонение слова «лид» по числу: 1 лид, 2 лида, 5 лидов.

    Общий хелпер для Telegram-отчётов (Live-паузы, бизнес-причины decision_policy),
    чтобы «8 лидов» / «1 лид» / «2 лида» читались грамматически верно.
    None трактуем как 0 → «лидов» (вызывающий сам решает, показывать ли число).
    """
    n = abs(int(n or 0))
    if n % 10 == 1 and n % 100 != 11:
        return "лид"
    if 2 <= n % 10 <= 4 and not (12 <= n % 100 <= 14):
        return "лида"
    return "лидов"
