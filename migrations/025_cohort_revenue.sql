-- Волна 4 недельных когорт: выручка и ROMI внутри строки (объявление, неделя).
--
-- Почему этого не было в волне 1. Выручку сознательно не брали: не был известен
-- лаг «лид → оплата», а services/cdp_client.get_payments фильтрует платежи по
-- doc_date — дате платёжного ДОКУМЕНТА. Приписать кассу недели W расходу недели
-- W значит вернуть ровно то усреднение, от которого уходим: деньги пришли за
-- лид, приведённый месяцем раньше, и «ROMI недели» оказался бы про чужую неделю.
--
-- Что изменилось. Замер лага на исторических платежах (сопоставление с лидами
-- по contract_number): медиана — несколько дней, к 14-му дню приходит около
-- 90% оплат, к 30-му — почти все. Лаг короткий — недельный ROMI считать можно.
--
-- Как считается. Выручка КОГОРТНАЯ, а не касса недели: деньги, пришедшие от
-- лидов, СОЗДАННЫХ на этой неделе, собранные за фиксированный горизонт H дней
-- после создания каждого лида (services/cohort_builder.REVENUE_HORIZON_DAYS,
-- сейчас 14 → около 90% денег). Горизонт хранится в строке: сравнивать между собой
-- можно только недели с одинаковым revenue_horizon_days.
--
-- Полнота — та же дисциплина, что у волны 1 (правило NULL_COERCED_TO_ZERO в
-- services/approval_rules.py): незрелая когорта или недоступный источник дают
-- NULL, а НИКОГДА не 0. Ноль пишется только когда он доказан: горизонт закрыт,
-- платежи получены целиком, и по лидам недели денег действительно не пришло.
--
-- ВНИМАНИЕ: старый SQLite (<3.35) — НЕТ GENERATED-колонок, НЕТ DROP COLUMN,
-- НЕТ «ADD COLUMN IF NOT EXISTS». Идемпотентность обеспечивает runner
-- (services/database_migrations.py): версия применяется ровно один раз под
-- запись в schema_migrations. CHECK в ADD COLUMN допустим (см. миграцию 018);
-- до SQLite 3.37 он не проверяется на уже существующих строках, а у них все
-- новые колонки NULL — конфликта нет ни на какой версии.

-- Выручка когорты в ед. Может быть ОТРИЦАТЕЛЬНОЙ: возвраты вычитаются, и
-- сделка, съеденная рефандом, обязана уменьшить выручку, а не обнулиться.
-- NULL = «неизвестно» (когорта не дозрела / ERP недоступна), не «ноль денег».
ALTER TABLE ad_weekly_cohorts
ADD COLUMN revenue_lcy REAL;

-- Сколько сделок когорты оплачено (нетто по сделке > 0), а не сколько платёжных
-- документов: рассрочка банка даёт N документов на одну сделку.
ALTER TABLE ad_weekly_cohorts
ADD COLUMN payments INTEGER CHECK(payments IS NULL OR payments >= 0);

-- Горизонт сбора выручки в днях от создания лида. Часть определения метрики:
-- revenue_lcy за 14 дней и за 30 дней — разные числа, и сравнивать их нельзя.
ALTER TABLE ad_weekly_cohorts
ADD COLUMN revenue_horizon_days INTEGER
CHECK(revenue_horizon_days IS NULL OR revenue_horizon_days > 0);

-- Дозрела ли когорта: прошёл ли горизонт у САМОГО ПОЗДНЕГО лида недели
-- (воскресенье + H дней <= сегодня). Календарное свойство недели, поэтому
-- NOT NULL DEFAULT 0 — «не дозрела» верно и для строк, написанных волной 1.
ALTER TABLE ad_weekly_cohorts
ADD COLUMN revenue_mature INTEGER NOT NULL DEFAULT 0
CHECK(revenue_mature IN (0, 1));

-- Курс USD→LCY на дату недели, по которому расход переведён в ед. Хранится
-- в строке, потому что ROMI обязан быть воспроизводим: пересчёт год спустя по
-- сегодняшнему курсу дал бы другое число при тех же данных.
ALTER TABLE ad_weekly_cohorts
ADD COLUMN usd_lcy_rate REAL CHECK(usd_lcy_rate IS NULL OR usd_lcy_rate > 0);

-- ROMI, % = revenue_lcy / (spend_usd × usd_lcy_rate) × 100 (конвенция проекта:
-- окупаемость, 100% = в ноль; см. integrations/amo.calc_ad_metrics). Считается
-- ТОЛЬКО у дозревшей когорты с известными расходом и курсом — CHECK делает
-- «ROMI по недозревшей неделе» непредставимым на уровне схемы, а не только в
-- коде. Может быть отрицательным (возвраты перевесили приход) — нижней границы
-- намеренно нет.
ALTER TABLE ad_weekly_cohorts
ADD COLUMN romi_pct REAL CHECK(romi_pct IS NULL OR revenue_mature = 1);
